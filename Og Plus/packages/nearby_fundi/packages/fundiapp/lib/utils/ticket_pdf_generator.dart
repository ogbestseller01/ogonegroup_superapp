// lib/utils/ticket_pdf_generator.dart
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/job.dart';
import '../l10n/app_localizations.dart';

class TicketPdfGenerator {
  static Future<void> generateAndPrint(WorkTicket ticket, AppLocalizations l10n) async {
    final pdf = pw.Document();

    // Choose standard font (supports basic Latin, works out of the box)
    final font = await PdfGoogleFonts.openSansRegular();
    final fontBold = await PdfGoogleFonts.openSansBold();

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (pw.Context context) {
          return pw.Padding(
            padding: const pw.EdgeInsets.all(32),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                // ── Header with Company Name ──
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Column(
                      crossAxisAlignment: pw.CrossAxisAlignment.start,
                      children: [
                        pw.Text(
                          'OG ONE-GROUP',
                          style: pw.TextStyle(
                            font: fontBold,
                            fontSize: 20,
                            color: PdfColors.blue900,
                          ),
                        ),
                        pw.SizedBox(height: 4),
                        pw.Text(
                          l10n.ticketDetails,
                          style: pw.TextStyle(font: fontBold, fontSize: 16),
                        ),
                        pw.SizedBox(height: 2),
                        pw.Text(
                          ticket.ticketNumber,
                          style: pw.TextStyle(
                            font: font,
                            fontSize: 14,
                            color: PdfColors.grey700,
                          ),
                        ),
                      ],
                    ),
                    pw.Container(
                      padding: const pw.EdgeInsets.symmetric(horizontal: 12, vertical: 6),
                      decoration: pw.BoxDecoration(
                        color: PdfColors.blue50,
                        borderRadius: pw.BorderRadius.circular(8),
                      ),
                      child: pw.Text(
                        ticket.status.toUpperCase(),
                        style: pw.TextStyle(
                          font: fontBold,
                          fontSize: 12,
                          color: PdfColors.blue800,
                        ),
                      ),
                    ),
                  ],
                ),
                pw.Divider(thickness: 1.5, color: PdfColors.grey400),
                pw.SizedBox(height: 20),

                // ── Details ──
                _buildRow(l10n.title, ticket.title, font, fontBold),
                if (ticket.description != null)
                  _buildRow(l10n.description, ticket.description!, font, fontBold),
                _buildRow(l10n.jobs, ticket.jobNumber ?? '—', font, fontBold),
                if (ticket.jobStatus != null)
                  _buildRow(l10n.jobStatus, ticket.jobStatus!, font, fontBold),
                _buildRow(l10n.customer, ticket.customerName ?? '—', font, fontBold),
                _buildRow(l10n.service, ticket.serviceName ?? '—', font, fontBold),
                _buildRow(l10n.ticketStatus, ticket.status, font, fontBold),

                pw.SizedBox(height: 20),
                pw.Divider(thickness: 1, color: PdfColors.grey300),

                // ── Dates ──
                if (ticket.createdAt != null)
                  _buildRow(l10n.created, ticket.createdAt!.toLocal().toString().split('.')[0], font, fontBold),
                if (ticket.completedAt != null)
                  _buildRow(l10n.completedLabel, ticket.completedAt!.toLocal().toString().split('.')[0], font, fontBold),

                pw.Spacer(),
                pw.Divider(thickness: 1, color: PdfColors.grey300),
                pw.SizedBox(height: 8),
                pw.Center(
                  child: pw.Text(
                    'Generated by OG ONE-GROUP • FundiApp',
                    style: pw.TextStyle(font: font, fontSize: 10, color: PdfColors.grey500),
                  ),
                ),
              ],
            ),
          );
        },
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: '${ticket.ticketNumber}.pdf',
    );
  }

  static pw.Widget _buildRow(String label, String value, pw.Font font, pw.Font fontBold) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 12),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 120,
            child: pw.Text(
              label,
              style: pw.TextStyle(font: fontBold, fontSize: 12, color: PdfColors.grey700),
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              value,
              style: pw.TextStyle(font: font, fontSize: 12),
            ),
          ),
        ],
      ),
    );
  }
}